    fn check_chain(seed_hex: &str, chain: &[(&str, &str, &str)]) {
        let seed = hex::decode(seed_hex).unwrap();
        let master = ExtendedKey::master(&seed, xprv()).unwrap();
        for (path, xpub, xprv) in chain {
            let key = master.derive_path(&parse_path(path).unwrap()).unwrap();
            assert_eq!(key.encode(), *xprv, "{path}");
            assert_eq!(key.to_public().encode(), *xpub, "{path}");
            let parsed = ExtendedKey::parse(xprv.as_bytes()).unwrap();
            assert_eq!(parsed, key);
            assert_eq!(ExtendedKey::parse(xpub.as_bytes()).unwrap(), key.to_public());
        }
    }


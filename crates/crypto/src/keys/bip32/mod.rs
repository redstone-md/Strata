    #[test]
    fn public_derivation_matches_private() {
        let seed = hex::decode("000102030405060708090a0b0c0d0e0f").unwrap();
        let m = ExtendedKey::master(&seed, xprv()).unwrap();
        let a = m.derive_path(&[HARDENED, 1, 2]).unwrap().to_public();
        let b = m.derive_child(HARDENED).unwrap().to_public().derive_path(&[1, 2]).unwrap();
        assert_eq!(a.encode(), b.encode());
        assert!(b.derive_child(HARDENED).is_none());
    }


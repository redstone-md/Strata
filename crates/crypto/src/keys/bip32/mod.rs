    #[test]
    fn standard_paths_bip84_bip86() {
        // BIP84 / BIP86 vectors from "abandon x11 about".
        let seed = crate::keys::mnemonic::Bip39Mnemonic::parse(
            "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about",
        )
        .unwrap()
        .to_seed("");
        let m = ExtendedKey::master(&seed, xprv()).unwrap();
        let addrs = DerivationPlan::new(1).derive(&m);
        let find = |p: &str| addrs.iter().find(|a| a.path() == p).unwrap().address().to_string();
        assert_eq!(find("m/84'/0'/0'/0/0"), "bc1qcr8te4kr609gcawutmrza0j4xv80jy8z306fyu");
        assert_eq!(find("m/86'/0'/0'/0/0"), "bc1p5cyxnuxmeuwuvkwfem96lqzszd02n6xdcjrs20cac6yqjjwudpxqkedrcr");
        assert_eq!(find("m/49'/0'/0'/0/0"), "37VucYSaXLCAsxYyAPfbSi9eh4iEcbShgf");
        assert_eq!(find("m/44'/0'/0'/0/0"), "1LqBGSKuX5yYUonjxT5qGfpUsXKYYWeabA");
    }
